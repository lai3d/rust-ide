import Foundation
import Testing
@testable import RustIDECore

@Suite struct CargoDependencyTests {
    @Test func parsesDependenciesAndFeatures() throws {
        let json = #"""
        {"packages":[{"name":"app","manifest_path":"/w/app/Cargo.toml",
          "features":{"default":["json"],"json":["dep:serde_json"],"fast":[]},
          "dependencies":[
            {"name":"serde","source":"registry+https://github.com/rust-lang/crates.io-index","req":"^1.0","kind":null,
             "rename":null,"optional":false,"features":["derive"],"target":null},
            {"name":"serde_json","source":"registry+https://github.com/rust-lang/crates.io-index","req":"^1","kind":null,
             "optional":true,"features":[],"target":null},
            {"name":"util","source":null,"req":"*","kind":null,"optional":false,"features":[],"path":"/w/util"},
            {"name":"pretty_assertions","source":"registry+x","req":"^1.4","kind":"dev","optional":false,"features":[]},
            {"name":"cc","source":"registry+x","req":"^1","kind":"build","optional":false,"features":[]},
            {"name":"mio","source":"git+https://github.com/tokio-rs/mio","req":"*","kind":null,"rename":"io",
             "optional":false,"features":[],"target":"cfg(unix)"}],
          "targets":[{"name":"app","kind":["bin"],"src_path":"/w/app/src/main.rs"}]}],
         "workspace_root":"/w","target_directory":"/w/target","version":1}
        """#
        let package = try #require(CargoMetadata.parse(Data(json.utf8))?.packages.first)
        #expect(package.features == ["fast", "json"])
        #expect(package.defaultFeatures == ["json"])
        #expect(package.featureMap["json"] == ["dep:serde_json"])
        #expect(package.featureKey("fast") == "app/fast")
        #expect(package.directory == "/w/app")

        let byName = Dictionary(uniqueKeysWithValues: package.dependencies.map { ($0.name, $0) })
        #expect(byName["serde"] == CargoDependency(name: "serde", req: "^1.0", features: ["derive"]))
        #expect(byName["serde_json"]?.optional == true)
        #expect(byName["util"]?.source == .path("/w/util"))
        #expect(byName["pretty_assertions"]?.kind == .dev)
        #expect(byName["cc"]?.kind == .build && byName["cc"]?.kind.flag == "--build")
        #expect(byName["mio"]?.source == .git("https://github.com/tokio-rs/mio"))
        #expect(byName["mio"]?.rename == "io" && byName["mio"]?.target == "cfg(unix)")
        #expect(Set(package.dependencies.map(\.id)).count == package.dependencies.count)
    }

    @Test func readsLockedVersions() {
        let lock = """
            # This file is automatically @generated by Cargo.
            version = 4

            [[package]]
            name = "app"
            version = "0.1.0"
            dependencies = [
             "rand 0.7.3",
             "rand 0.8.5",
            ]

            [[package]]
            name = "rand"
            version = "0.7.3"
            source = "registry+https://github.com/rust-lang/crates.io-index"
            checksum = "abc"

            [[package]]
            name = "rand"
            version = "0.8.5"

            [metadata]
            name = "ignored"
            """
        let versions = CargoLock.versions(in: lock)
        #expect(versions["app"] == ["0.1.0"])
        #expect(versions["rand"] == ["0.7.3", "0.8.5"])
        #expect(versions["ignored"] == nil)
        #expect(versions.count == 2)
    }

    @Test func featuresReachRustAnalyzerSettings() {
        let settings = RustAnalyzerSettings.make(features: ["app/fast"])
        #expect(settings["cargo"]?["features"]?.arrayValue?.compactMap(\.stringValue) == ["app/fast"])
        #expect(settings["cargo"]?["buildScripts"]?["enable"]?.boolValue == true)
    }
}
